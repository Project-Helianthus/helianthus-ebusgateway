class MatrixError(ValueError):
    """The matrix file cannot be read as one JSON document without duplicate keys."""


def _unique_pairs(pairs):
    seen = {}
    for key, value in pairs:
        if key in seen:
            raise MatrixError(f"duplicate key {key!r}: every member and every cell appears once")
        seen[key] = value
    return seen


def load(path):
    try:
        text = pathlib.Path(path).read_text(encoding="utf-8")
    except OSError as error:
        raise MatrixError(f"cannot read {path}: {error.strerror}") from error
    try:
        return json.loads(text, object_pairs_hook=_unique_pairs)
    except json.JSONDecodeError as error:
        raise MatrixError(f"{path} is not JSON: {error.msg} at line {error.lineno}") from error


def _one_line(value):
    return isinstance(value, str) and bool(value.strip()) and "\n" not in value and "\r" not in value


def _member_ids(name, entries, errors):
    if not isinstance(entries, list) or not entries:
        errors.append(f"{name} must be a non-empty list")
        return []
    ids = []
    for index, entry in enumerate(entries):
        if not isinstance(entry, dict) or set(entry) != set(MEMBER_KEYS[name]):
            errors.append(f"{name}[{index}] must be an object with exactly the keys {', '.join(MEMBER_KEYS[name])}")
            continue
        member = entry["id"]
        if not isinstance(member, str) or not MEMBER_ID.fullmatch(member):
            errors.append(f"{name}[{index}] needs an id of lower-case letters, digits and underscores")
            continue
        if not _one_line(entry["title"]):
            errors.append(f"{name} {member} needs a one-line title")
        if "release" in entry and entry["release"] not in RELEASES:
            errors.append(f"{name} {member} has unknown release {entry['release']!r}")
        if member in ids:
            errors.append(f"{name} {member} is declared twice")
        ids.append(member)
    return ids


def _expected_keys(rows, columns):
    if columns is None:
        return [(row,) for row in rows]
    return [(row, column) for row in rows for column in columns]


def _flatten(axis, table, rows, columns, errors):
    if columns is None:
        return {(key,): value for key, value in table.items()}
    flat = {}
    for row, line in table.items():
        if row not in rows:
            errors.append(f"{axis} {row} names an unknown member")
        elif not isinstance(line, dict):
            errors.append(f"{axis} {row} must be an object of cells")
        else:
            flat.update({(row, column): value for column, value in line.items()})
    return flat


def axis_cells(axis, table, rows, columns, errors):
    """Return [(label, cell)] in declaration order; record missing and unknown cells."""
    if not isinstance(table, dict):
        errors.append(f"cells.{axis} must be an object")
        return []
    flat = _flatten(axis, table, rows, columns, errors)
    expected = _expected_keys(rows, columns)
    for key in flat:
        if key not in expected:
            errors.append(f"{axis} {' x '.join(key)} names an unknown member")
    present = []
    for key in expected:
        if key in flat:
            present.append((f"{axis} {' x '.join(key)}", flat[key]))
        else:
            errors.append(f"{axis} {' x '.join(key)} has no cell")
    return present


def _read(path):
    try:
        return path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return None


def _blank(match):
    return re.sub(r"[^\n]", " ", match.group(0))


def go_code(text):
    """Return Go source with comments and string and rune literals blanked, line breaks kept."""
    return GO_COMMENT_OR_LITERAL.sub(_blank, text)


def _go_declares(path, function):
    text = _read(path)
    pattern = rf"^func[ \t]+{function}[ \t]*\({GO_TEST_PARAMETER}\)"
    return text is not None and re.search(pattern, go_code(text), flags=re.MULTILINE) is not None


def _file_name_matches(name, goarch):
    """Apply go/build's file-name rule: a _GOOS, _GOARCH or _GOOS_GOARCH suffix restricts the file."""
    if name.startswith(("_", ".")):
        return False
    stem = name.split(".", 1)[0]
    if "_" not in stem:
        return True
    parts = stem[stem.index("_"):].split("_")
    if parts[-1] == "test":
        parts = parts[:-1]
    if len(parts) >= 2 and parts[-2] in KNOWN_GOOS and parts[-1] in KNOWN_GOARCH:
        return parts[-2] == RELEASE_GOOS and parts[-1] == goarch
    if parts and parts[-1] in KNOWN_GOOS:
        return parts[-1] == RELEASE_GOOS
    if parts and parts[-1] in KNOWN_GOARCH:
        return parts[-1] == goarch
    return True


def _header_constraints(text):
    """Return the //go:build expressions and the // +build lines before the package clause.

    A // +build line counts only when a blank line follows it before the package clause; go
    vet (run by go test) refuses a file whose // +build line runs straight into the package
    clause ('misplaced +build comment'), so such a line raises ValueError.
    """
    expressions, legacy = [], []
    in_block = False
    plus_build_awaits_blank_line = False
    for line in text.splitlines():
        stripped = line.strip()
        if in_block:
            in_block = "*/" not in stripped
            continue
        if not stripped:
            plus_build_awaits_blank_line = False
            continue
        if stripped.startswith("/*"):
            in_block = "*/" not in stripped[2:]
            continue
        if not stripped.startswith("//"):
            break
        body = stripped[2:]
        if body.startswith("go:build") and (len(body) == 8 or body[8] in " \t"):
            expressions.append(body[8:].strip())
        elif body.strip().startswith("+build"):
            legacy.append(body.strip()[6:].strip())
            plus_build_awaits_blank_line = True
    if plus_build_awaits_blank_line:
        raise ValueError("misplaced +build comment: no blank line before the package clause")
    return expressions, legacy


class _BuildExpression:
    """Parse one //go:build expression into a tree; any syntax error raises ValueError.

    A node is ("tag", name), ("not", x), ("and", x, y) or ("or", x, y), built left-associative
    as go/build/constraint builds it.
    """

    def __init__(self, text):
        self.tokens = []
        position = 0
        while position < len(text):
            match = GO_BUILD_TOKEN.match(text, position)
            if match is None:
                if text[position:].strip():
                    raise ValueError(text)
                break
            self.tokens.append(match.group(1))
            position = match.end()
        self.index = 0

    def tree(self):
        result = self._or()
        if self.index != len(self.tokens):
            raise ValueError("trailing tokens")
        return result

    def _next(self):
        if self.index >= len(self.tokens):
            raise ValueError("unexpected end")
        token = self.tokens[self.index]
        self.index += 1
        return token

    def _peek(self):
        return self.tokens[self.index] if self.index < len(self.tokens) else None

    def _or(self):
        result = self._and()
        while self._peek() == "||":
            self._next()
            result = ("or", result, self._and())
        return result

    def _and(self):
        result = self._not()
        while self._peek() == "&&":
            self._next()
            result = ("and", result, self._not())
        return result

    def _not(self):
        token = self._next()
        if token == "!":
            if self._peek() == "!":
                raise ValueError("double negation not allowed")
            return ("not", self._not())
        if token == "(":
            result = self._or()
            if self._next() != ")":
                raise ValueError("unbalanced parenthesis")
            return result
        if token in ("||", "&&", ")"):
            raise ValueError("operator without operand")
        return ("tag", token)


def _evaluate(node, tags):
    kind = node[0]
    if kind == "tag":
        return node[1] in tags
    if kind == "not":
        return not _evaluate(node[1], tags)
    if kind == "and":
        return _evaluate(node[1], tags) and _evaluate(node[2], tags)
    return _evaluate(node[1], tags) or _evaluate(node[2], tags)


def _render(node):
    """The constraint's String form: ! binds a tag or a parenthesised group, && parenthesises ||."""
    kind = node[0]
    if kind == "tag":
        return node[1]
    if kind == "not":
        inner = _render(node[1])
        return "!" + (f"({inner})" if node[1][0] in ("and", "or") else inner)
    other = "or" if kind == "and" else "and"
    operator = " && " if kind == "and" else " || "
    return operator.join(f"({_render(arg)})" if arg[0] == other else _render(arg) for arg in node[1:])


def _join(kind, nodes):
    result = None
    for node in nodes:
        result = node if result is None else (kind, result, node)
    return result


def _legacy_line_tree(line):
    """A // +build line: space-separated options are ORed, comma-separated terms are ANDed."""
    def term(word):
        negated = word.startswith("!")
        name = word[1:] if negated else word
        if not name or not re.fullmatch(r"[A-Za-z0-9_.]+", name):
            raise ValueError(word)
        return ("not", ("tag", name)) if negated else ("tag", name)
    options = [_join("and", [term(word) for word in option.split(",")]) for option in line.split()]
    if not options:
        raise ValueError("empty +build line")
    return _join("or", options)


def _push_not(node, negate):
    kind = node[0]
    if kind == "tag":
        return ("not", node) if negate else node
    if kind == "not":
        if node[1][0] == "tag" and not negate:
            return node
        return _push_not(node[1], not negate)
    left, right = _push_not(node[1], negate), _push_not(node[2], negate)
    if negate:
        kind = "or" if kind == "and" else "and"
    return (kind, left, right)


def _split(kind, node):
    if node[0] == kind:
        return _split(kind, node[1]) + _split(kind, node[2])
    return [node]


def _plus_build_trees(expression):
    """The // +build lines that go/build/constraint derives from a //go:build tree, parsed back.

    ValueError when the expression is too complex for // +build lines.
    """
    split = []
    for disjunction in _split("and", _push_not(expression, False)):
        clauses = []
        for conjunction in _split("or", disjunction):
            literals = _split("and", conjunction)
            if any(literal[0] not in ("tag", "not") for literal in literals):
                raise ValueError("expression too complex for // +build lines")
            clauses.append(literals)
        split.append(clauses)
    if max(len(clauses) for clauses in split) == 1:
        split = [[[literal for clauses in split for literal in clauses[0]]]]
    return [_join("or", [_join("and", literals) for literals in clauses]) for clauses in split]


def _constraint_tree(expressions, legacy):
    """The file's build constraint, or ValueError when go test would refuse its header.

    With both forms present, go vet (run by go test) requires the // +build lines to equal the
    lines derived from the //go:build expression; this compares them as vet does.
    """
    if expressions:
        tree = _BuildExpression(expressions[0]).tree()
        if legacy:
            plus_build = _join("and", [_legacy_line_tree(line) for line in legacy])
            if _render(_join("and", _plus_build_trees(tree))) != _render(plus_build):
                raise ValueError("+build lines do not match //go:build condition")
        return tree
    if legacy:
        return _join("and", [_legacy_line_tree(line) for line in legacy])
    return None


def _release_go_minor(root):
    text = _read(pathlib.Path(root, "go.mod"))
    match = GO_DIRECTIVE.search(text or "")
    return int(match.group(1)) if match else 0


def _release_tags(goarch, race, go_minor, features=()):
    tags = {RELEASE_GOOS, "unix", "gc", goarch}
    tags.update(features)
    tags.update(f"go1.{minor}" for minor in range(1, go_minor + 1))
    if race:
        tags.add("race")
    return tags


def in_release_build(root, path):
    """True when the Go file is in the linux build of every release architecture, with and without -race.

    Each architecture's build sets its release feature tags (RELEASE_FEATURE_LEVELS). Release tags go1.N are set only up to the go directive of the root go.mod, the minimum any
    building toolchain provides; cgo and every custom tag are unset. An unreadable file or an
    unparsable constraint is never in the build.
    """
    text = _read(path)
    if text is None:
        return False
    try:
        expressions, legacy = _header_constraints(text)
        if len(expressions) > 1:
            return False
        constraint = _constraint_tree(expressions, legacy)
    except ValueError:
        return False
    go_minor = _release_go_minor(root)
    for goarch in RELEASE_GOARCHES:
        if not _file_name_matches(path.name, goarch):
            return False
        for features in RELEASE_FEATURE_LEVELS[goarch]:
            for race in (False, True):
                tags = _release_tags(goarch, race, go_minor, features)
                if constraint is not None and not _evaluate(constraint, tags):
                    return False
    return True


def _import_bindings(node):
    """Yield (bound name, dotted target) for one import; a relative import's target is None."""
    for alias in node.names:
        if isinstance(node, ast.Import):
            head = alias.name.split(".")[0]
            yield (alias.asname, alias.name) if alias.asname else (head, head)
        elif node.level or node.module is None:
            yield alias.asname or alias.name, None
        else:
            yield alias.asname or alias.name, f"{node.module}.{alias.name}"


def _module_imports(statements, bound):
    """Map each module-level name an import binds to the dotted name it refers to."""
    for node in statements:
        if isinstance(node, (ast.Import, ast.ImportFrom)):
            bound.update(_import_bindings(node))
        elif isinstance(node, (ast.If, ast.Try, ast.With)):
            for block in ("body", "orelse", "finalbody"):
                _module_imports(getattr(node, block, []), bound)
            for handler in getattr(node, "handlers", []):
                _module_imports(handler.body, bound)
    return bound


def _resolved_base(base, imports):
    """Return the dotted name a class base refers to, following the module's import aliases."""
    text = ast.unparse(base)
    head, _, rest = text.partition(".")
    if head not in imports:
        return text
    target = imports[head]
    if target is None:
        return None
    return f"{target}.{rest}" if rest else target


def _class_body_names(node):
    """Map each name the class body binds (def or plain assignment) to its value node, or None for a def."""
    bound = {}
    for item in node.body:
        if isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef)):
            bound[item.name] = None
        elif isinstance(item, ast.Assign):
            for target in item.targets:
                if isinstance(target, ast.Name):
                    bound[target.id] = item.value
        elif isinstance(item, ast.AnnAssign) and isinstance(item.target, ast.Name) and item.value is not None:
            bound[item.target.id] = item.value
    return bound


def _collected_classes(tree):
    """Return the names of the module-level classes the test runner collects.

    A class whose __test__ attribute, set in its body or inherited from a base class of the same
    module, is not a true constant is never collected. A class that unittest.TestCase does not
    underlie is collected only when it is named Test... and neither it nor a base class of the
    same module defines __init__ or __new__ (pytest refuses a class with a constructor).
    """
    collected = set()
    # Module-level class name -> (derives from unittest.TestCase, __test__ value or None, has a constructor).
    defined = {}
    imports = _module_imports(tree.body, {})
    for node in tree.body:
        if not isinstance(node, ast.ClassDef):
            continue
        bases = {_resolved_base(base, imports) for base in node.bases}
        local_bases = [defined[base.id] for base in node.bases
                       if isinstance(base, ast.Name) and base.id not in imports and base.id in defined]
        bound = _class_body_names(node)
        test_case = bool(bases & PYTHON_TEST_CASE_BASES) or any(base[0] for base in local_bases)
        if "__test__" in bound:
            value = bound["__test__"]
            opted_in = isinstance(value, ast.Constant) and bool(value.value)
        else:
            opted_in = next((base[1] for base in local_bases if base[1] is not None), None)
        constructor = "__init__" in bound or "__new__" in bound or any(base[2] for base in local_bases)
        defined[node.name] = (test_case, opted_in, constructor)
        if opted_in is False:
            continue
        if test_case or (node.name.startswith("Test") and not constructor):
            collected.add(node.name)
    return collected


def _python_collects(path, function):
    """True when the runner collects a test of that name: module level, or a method of a collected class."""
    text = _read(path)
    if text is None:
        return False
    try:
        tree = ast.parse(text, filename=str(path))
    except (SyntaxError, ValueError):
        return False
    functions = (ast.FunctionDef, ast.AsyncFunctionDef)
    collected = _collected_classes(tree)
    for node in tree.body:
        if isinstance(node, functions) and node.name == function:
            return True
        if isinstance(node, ast.ClassDef) and node.name in collected:
            if any(isinstance(item, functions) and item.name == function for item in node.body):
                return True
    return False


def missing_test(root, name):
    """Return why the named test does not exist, or None when it exists."""
    parts = name.split()
    if len(parts) != 2 or not FUNCTION_NAME.fullmatch(parts[1]):
        return "names a test as '<package directory> <TestName>' or '<script path> <test_name>'"
    location, function = parts
    relative = pathlib.PurePosixPath(location)
    if relative.is_absolute() or ".." in relative.parts or "\\" in location:
        return f"names a test outside the repository: {location}"
    target = pathlib.Path(root, *relative.parts)
    if location.endswith(".py"):
        if not PYTHON_TEST_NAME.fullmatch(function):
            return f"names {function}, which the test runner does not collect: a Python test name starts with test"
        if target.is_file() and _python_collects(target, function):
            return None
        return (f"names {function} but {location} declares no def {function}( that the test runner collects "
                "(module level, or a method of a collected test class)")
    if not GO_TEST_NAME.fullmatch(function):
        return f"names {function}, which go test does not run: a Go test name is Test or Test followed by a non-lower-case character"
    tests = sorted(target.glob("*_test.go")) if target.is_dir() else []
    declaring = [path for path in tests if _go_declares(path, function)]
    if any(in_release_build(root, path) for path in declaring):
        return None
    if declaring:
        return (f"names {function} but every _test.go file in {location} that declares it is excluded from the "
                f"{RELEASE_GOOS} release build by a build constraint or its file name")
    return f"names {function} but no _test.go file in {location} declares func {function}(t *testing.T)"


def _state_rule(label, cell, root):
    state = cell["state"]
    if state == "pass":
        if cell["test"] is None:
            return f"{label} is pass without a test"
        problem = missing_test(root, cell["test"])
        return f"{label} {problem}" if problem else None
    if state in ("not_applicable", "not_in_0_7") and not _one_line(cell["reason"]):
        return f"{label} is {state} without a one-line reason"
    if state != "pass" and cell["test"] is not None:
        return f"{label} is {state} and names a test; only a pass cell names a test"
    if state == "not_in_0_7" and cell["issue"] is None:
        return f"{label} is not_in_0_7 without an owner issue in the form <repo>#<number>"
    return None


def cell_problem(label, cell, root):
    if not isinstance(cell, dict) or set(cell) != set(CELL_KEYS):
        return f"{label} must be an object with exactly the keys {', '.join(CELL_KEYS)}"
    if cell["state"] not in STATES:
        return f"{label} has unknown state {cell['state']!r}"
    for key in ("test", "reason", "issue"):
        if cell[key] is not None and not _one_line(cell[key]):
            return f"{label} {key} must be null or a one-line, non-empty string"
    if cell["issue"] is not None and not OWNER_ISSUE.fullmatch(cell["issue"]):
        return f"{label} issue {cell['issue']!r} is not in the form <repo>#<number>"
    return _state_rule(label, cell, root)


def validate(document, root):
    """Return every rule violation of the matrix; an empty list means it is valid."""
    if not isinstance(document, dict):
        return ["the matrix must be a JSON object"]
    errors = []
    if document.get("format") != FORMAT:
        errors.append(f"format must be {FORMAT}")
    for key in sorted(set(document) - set(TOP_KEYS)):
        errors.append(f"{key} is not a matrix key")
    ids = {name: _member_ids(name, document.get(name), errors) for name in MEMBER_KEYS}
    cells = document.get("cells")
    if not isinstance(cells, dict):
        return errors + ["cells must be an object"]
    for axis in sorted(set(cells) - set(AXES)):
        errors.append(f"cells.{axis} is not an axis")
    for axis, (rows, columns) in AXES.items():
        column_ids = ids[columns] if columns else None
        for label, cell in axis_cells(axis, cells.get(axis), ids[rows], column_ids, errors):
            problem = cell_problem(label, cell, root)
            if problem:
                errors.append(problem)
    return errors


def axis_states(document):
    """Return {axis: [(label, cell)]} of a valid matrix in declaration order."""
    result = {}
    for axis, (rows, columns) in AXES.items():
        row_ids = [member["id"] for member in document[rows]]
        column_ids = [member["id"] for member in document[columns]] if columns else None
        result[axis] = axis_cells(axis, document["cells"][axis], row_ids, column_ids, [])
    return result


def _escape(text):
    return "" if text is None else str(text).replace("|", "\\|")


def _table(header, rows):
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines.extend("| " + " | ".join(_escape(value) for value in row) + " |" for row in rows)
    return lines + [""]


def _counts_table(cells_by_axis):
    rows = []
    totals = [0] * (len(STATES) + 1)
    for axis, cells in cells_by_axis.items():
        counts = [len(cells)] + [sum(1 for _, cell in cells if cell["state"] == s) for s in STATES]
        totals = [a + b for a, b in zip(totals, counts)]
        rows.append([f"`{axis}`"] + [str(value) for value in counts])
    rows.append(["total"] + [str(value) for value in totals])
    return _table(["Axis", "Cells"] + [f"`{s}`" for s in STATES], rows)


def _grid(document, axis, columns):
    column_ids = [member["id"] for member in document[columns]]
    rows = []
    for family in document["families"]:
        line = document["cells"][axis][family["id"]]
        rows.append([f"`{family['id']}`"] + [f"`{line[column]['state']}`" for column in column_ids])
    return _table(["Family"] + [f"`{column}`" for column in column_ids], rows)


def _members(document, name, header):
    keys = MEMBER_KEYS[name][1:]
    rows = [[f"`{member['id']}`"] + [member[key] if key == "title" else f"`{member[key]}`" for key in keys]
            for member in document[name]]
    return _table(header, rows)


def _details(cells_by_axis):
    rows = []
    for cells in cells_by_axis.values():
        for label, cell in cells:
            if cell["state"] != "not_run" or cell["test"] or cell["reason"] or cell["issue"]:
                rows.append([label, f"`{cell['state']}`", cell["test"] or "", cell["reason"] or "",
                             cell["issue"] or ""])
    if not rows:
        return ["Every cell is `not_run` and carries no test, reason or issue.", ""]
    return _table(["Cell", "State", "Test", "Reason", "Owner issue"], rows)


def render(document):
    """Return the page's generated tables for a valid matrix."""
    cells_by_axis = axis_states(document)
    negatives = [[f"`{member['id']}`", member["title"],
                  f"`{document['cells']['graph_negative'][member['id']]['state']}`"]
                 for member in document["graph_negatives"]]
    lines = ["### Cell counts", ""] + _counts_table(cells_by_axis)
    lines += ["### Families", ""] + _members(document, "families", ["Family", "Title", "Release"])
    lines += ["### Surfaces", ""] + _members(document, "surfaces", ["Surface", "Title"])
    lines += ["### Graph rows", ""] + _members(document, "graph_rows", ["Graph row", "Title"])
    lines += ["### Conditions", ""] + _members(document, "conditions", ["Condition", "Title"])
    lines += ["### Family x surface", ""] + _grid(document, "family_surface", "surfaces")
    lines += ["### Family x graph", ""] + _grid(document, "family_graph", "graph_rows")
    lines += ["### Family x condition", ""] + _grid(document, "family_condition", "conditions")
    lines += ["### Graph negatives", ""] + _table(["Graph negative", "Title", "State"], negatives)
    lines += ["### Cells with a test, a reason or an owner issue", ""] + _details(cells_by_axis)
    return "\n".join(lines).rstrip("\n") + "\n"


def generated_section(text):
    """Return the page text between the two marker lines, or None without both markers."""
    lines = text.split("\n")
    if lines.count(BEGIN) != 1 or lines.count(END) != 1:
        return None
    begin, end = lines.index(BEGIN), lines.index(END)
    if end < begin:
        return None
    return "\n".join(lines[begin + 1:end])


def page_problem(document, page):
    try:
        text = pathlib.Path(page).read_text(encoding="utf-8")
    except OSError as error:
        return f"cannot read {page}: {error.strerror}"
    section = generated_section(text)
    if section is None:
        return f"{page} needs exactly one generated section between the marker lines {BEGIN} and {END}"
    if section.strip("\n") != render(document).strip("\n"):
        return (f"the generated tables of {page} differ from the matrix; "
                "replace them with the output of scripts/offline_acceptance_matrix.py render")
    return None


def _report(messages):
    for message in messages:
        print(PREFIX + message, file=sys.stderr)
    return 1 if messages else 0


def run_check(root, matrix, page, require_complete):
    document = load(matrix)
    errors = validate(document, root)
    if errors:
        return _report(errors)
    problem = page_problem(document, page)
    if problem:
        return _report([problem])
    cells_by_axis = axis_states(document)
    open_cells = {axis: sum(1 for _, c in cells if c["state"] == "not_run") for axis, cells in cells_by_axis.items()}
    total = sum(len(cells) for cells in cells_by_axis.values())
    per_axis = ", ".join(f"{axis} {count}" for axis, count in open_cells.items())
    if require_complete and any(open_cells.values()):
        return _report([f"incomplete: {sum(open_cells.values())} cells not_run ({per_axis})"])
    print(f"{PREFIX}ok: {total} cells, {sum(open_cells.values())} not_run ({per_axis})")
    return 0


def run_render(root, matrix):
    document = load(matrix)
    errors = validate(document, root)
    if errors:
        return _report(errors)
    sys.stdout.write(render(document))
    return 0


def parse_arguments(argv):
    common = argparse.ArgumentParser(add_help=False)
    common.add_argument("--root", default=str(ROOT), help="repository root that named tests are resolved against")
    common.add_argument("--matrix", help="matrix file (default: " + MATRIX_PATH + " under the root)")
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    commands = parser.add_subparsers(dest="command", required=True)
    check = commands.add_parser("check", parents=[common], help="validate the matrix and the page")
    check.add_argument("--page", help="page file (default: " + PAGE_PATH + " under the root)")
    check.add_argument("--require-complete", action="store_true", help="also fail on any not_run cell")
    commands.add_parser("render", parents=[common], help="print the page's generated tables")
    return parser.parse_args(argv)


def main(argv=None):
    arguments = parse_arguments(argv)
    root = pathlib.Path(arguments.root)
    matrix = pathlib.Path(arguments.matrix) if arguments.matrix else root / MATRIX_PATH
    try:
        if arguments.command == "render":
            return run_render(root, matrix)
        page = pathlib.Path(arguments.page) if arguments.page else root / PAGE_PATH
        return run_check(root, matrix, page, arguments.require_complete)
    except MatrixError as error:
        return _report([str(error)])


if __name__ == "__main__":
    sys.exit(main())
