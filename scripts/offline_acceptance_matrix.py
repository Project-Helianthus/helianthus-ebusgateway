#!/usr/bin/env python3
"""Validate and render the offline acceptance matrix of the release.

check                     every axis member has exactly one cell, every cell is well
                          formed, every pass cell names an existing test, and the page's
                          generated tables equal the rendered tables
check --require-complete  also fails on any not_run cell and prints the count per axis
render                    prints the page's generated tables

A Go test is named as '<package directory> <TestName>' and exists when a _test.go
file in that directory declares the go test entry point 'func <TestName>(t *testing.T)',
where TestName is Test or Test followed by a non-lower-case character. A Python test
is named as '<script path> <test_name>' and exists when test_name starts with 'test'
and that file declares 'def <test_name>('. A helper function is never a test.
Standard library only.
"""

from __future__ import annotations

import argparse
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
MATRIX_PATH = "docs/testing/offline-acceptance-matrix.json"
PAGE_PATH = "docs/testing/offline-acceptance-matrix.md"
FORMAT = "helianthus-offline-acceptance-matrix/1"
PREFIX = "offline acceptance matrix: "
BEGIN = "<!-- offline-acceptance-matrix:begin (generated by scripts/offline_acceptance_matrix.py render) -->"
END = "<!-- offline-acceptance-matrix:end -->"
STATES = ("not_run", "pass", "not_applicable", "not_in_0_7")
RELEASES = ("in_0_7", "withheld_by_contract", "not_in_0_7")
CELL_KEYS = ("state", "test", "reason", "issue")
TOP_KEYS = ("format", "note", "families", "surfaces", "graph_rows", "graph_negatives", "conditions", "cells")
MEMBER_KEYS = {
    "families": ("id", "title", "release"),
    "surfaces": ("id", "title"),
    "graph_rows": ("id", "title"),
    "graph_negatives": ("id", "title"),
    "conditions": ("id", "title"),
}
# Cell axis -> (row member list, column member list or None for a single-member axis).
AXES = {
    "family_surface": ("families", "surfaces"),
    "family_graph": ("families", "graph_rows"),
    "family_condition": ("families", "conditions"),
    "graph_negative": ("graph_negatives", None),
}
MEMBER_ID = re.compile(r"[a-z][a-z0-9_]*")
FUNCTION_NAME = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")
# go test runs a top-level func TestXxx(t *testing.T) whose Xxx does not start with a lower-case letter.
GO_TEST_NAME = re.compile(r"Test(?:[^a-z].*)?")
GO_TEST_PARAMETER = r"[ \t]*[A-Za-z_][A-Za-z0-9_]*[ \t]+\*[ \t]*testing\.T[ \t]*"
# unittest and pytest collect only functions whose name starts with test.
PYTHON_TEST_NAME = re.compile(r"test[A-Za-z0-9_]*")
OWNER_ISSUE = re.compile(r"[a-z0-9][a-z0-9._-]*#[1-9][0-9]*")


class MatrixError(ValueError):
    """The matrix file cannot be read as one JSON document without duplicate keys."""


def _unique_pairs(pairs):
    seen = {}
    for key, value in pairs:
        if key in seen:
            raise MatrixError(f"duplicate key {key!r}: every member and every cell appears once")
        seen[key] = value
    return seen


def load(path):
    try:
        text = pathlib.Path(path).read_text(encoding="utf-8")
    except OSError as error:
        raise MatrixError(f"cannot read {path}: {error.strerror}") from error
    try:
        return json.loads(text, object_pairs_hook=_unique_pairs)
    except json.JSONDecodeError as error:
        raise MatrixError(f"{path} is not JSON: {error.msg} at line {error.lineno}") from error


def _one_line(value):
    return isinstance(value, str) and bool(value.strip()) and "\n" not in value and "\r" not in value


def _member_ids(name, entries, errors):
    if not isinstance(entries, list) or not entries:
        errors.append(f"{name} must be a non-empty list")
        return []
    ids = []
    for index, entry in enumerate(entries):
        if not isinstance(entry, dict) or set(entry) != set(MEMBER_KEYS[name]):
            errors.append(f"{name}[{index}] must be an object with exactly the keys {', '.join(MEMBER_KEYS[name])}")
            continue
        member = entry["id"]
        if not isinstance(member, str) or not MEMBER_ID.fullmatch(member):
            errors.append(f"{name}[{index}] needs an id of lower-case letters, digits and underscores")
            continue
        if not _one_line(entry["title"]):
            errors.append(f"{name} {member} needs a one-line title")
        if "release" in entry and entry["release"] not in RELEASES:
            errors.append(f"{name} {member} has unknown release {entry['release']!r}")
        if member in ids:
            errors.append(f"{name} {member} is declared twice")
        ids.append(member)
    return ids


def _expected_keys(rows, columns):
    if columns is None:
        return [(row,) for row in rows]
    return [(row, column) for row in rows for column in columns]


def _flatten(axis, table, rows, columns, errors):
    if columns is None:
        return {(key,): value for key, value in table.items()}
    flat = {}
    for row, line in table.items():
        if row not in rows:
            errors.append(f"{axis} {row} names an unknown member")
        elif not isinstance(line, dict):
            errors.append(f"{axis} {row} must be an object of cells")
        else:
            flat.update({(row, column): value for column, value in line.items()})
    return flat


def axis_cells(axis, table, rows, columns, errors):
    """Return [(label, cell)] in declaration order; record missing and unknown cells."""
    if not isinstance(table, dict):
        errors.append(f"cells.{axis} must be an object")
        return []
    flat = _flatten(axis, table, rows, columns, errors)
    expected = _expected_keys(rows, columns)
    for key in flat:
        if key not in expected:
            errors.append(f"{axis} {' x '.join(key)} names an unknown member")
    present = []
    for key in expected:
        if key in flat:
            present.append((f"{axis} {' x '.join(key)}", flat[key]))
        else:
            errors.append(f"{axis} {' x '.join(key)} has no cell")
    return present


def _declares(path, pattern):
    try:
        text = path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return False
    return re.search(pattern, text, flags=re.MULTILINE) is not None


def missing_test(root, name):
    """Return why the named test does not exist, or None when it exists."""
    parts = name.split()
    if len(parts) != 2 or not FUNCTION_NAME.fullmatch(parts[1]):
        return "names a test as '<package directory> <TestName>' or '<script path> <test_name>'"
    location, function = parts
    relative = pathlib.PurePosixPath(location)
    if relative.is_absolute() or ".." in relative.parts or "\\" in location:
        return f"names a test outside the repository: {location}"
    target = pathlib.Path(root, *relative.parts)
    if location.endswith(".py"):
        if not PYTHON_TEST_NAME.fullmatch(function):
            return f"names {function}, which the test runner does not collect: a Python test name starts with test"
        if target.is_file() and _declares(target, rf"^[ \t]*(?:async[ \t]+)?def[ \t]+{function}[ \t]*\("):
            return None
        return f"names {function} but {location} declares no def {function}("
    if not GO_TEST_NAME.fullmatch(function):
        return f"names {function}, which go test does not run: a Go test name is Test or Test followed by a non-lower-case character"
    tests = sorted(target.glob("*_test.go")) if target.is_dir() else []
    if any(_declares(path, rf"^func[ \t]+{function}[ \t]*\({GO_TEST_PARAMETER}\)") for path in tests):
        return None
    return f"names {function} but no _test.go file in {location} declares func {function}(t *testing.T)"


def _state_rule(label, cell, root):
    state = cell["state"]
    if state == "pass":
        if cell["test"] is None:
            return f"{label} is pass without a test"
        problem = missing_test(root, cell["test"])
        return f"{label} {problem}" if problem else None
    if state in ("not_applicable", "not_in_0_7") and not _one_line(cell["reason"]):
        return f"{label} is {state} without a one-line reason"
    if state != "pass" and cell["test"] is not None:
        return f"{label} is {state} and names a test; only a pass cell names a test"
    if state == "not_in_0_7" and cell["issue"] is None:
        return f"{label} is not_in_0_7 without an owner issue in the form <repo>#<number>"
    return None


def cell_problem(label, cell, root):
    if not isinstance(cell, dict) or set(cell) != set(CELL_KEYS):
        return f"{label} must be an object with exactly the keys {', '.join(CELL_KEYS)}"
    if cell["state"] not in STATES:
        return f"{label} has unknown state {cell['state']!r}"
    for key in ("test", "reason", "issue"):
        if cell[key] is not None and not _one_line(cell[key]):
            return f"{label} {key} must be null or a one-line, non-empty string"
    if cell["issue"] is not None and not OWNER_ISSUE.fullmatch(cell["issue"]):
        return f"{label} issue {cell['issue']!r} is not in the form <repo>#<number>"
    return _state_rule(label, cell, root)


def validate(document, root):
    """Return every rule violation of the matrix; an empty list means it is valid."""
    if not isinstance(document, dict):
        return ["the matrix must be a JSON object"]
    errors = []
    if document.get("format") != FORMAT:
        errors.append(f"format must be {FORMAT}")
    for key in sorted(set(document) - set(TOP_KEYS)):
        errors.append(f"{key} is not a matrix key")
    ids = {name: _member_ids(name, document.get(name), errors) for name in MEMBER_KEYS}
    cells = document.get("cells")
    if not isinstance(cells, dict):
        return errors + ["cells must be an object"]
    for axis in sorted(set(cells) - set(AXES)):
        errors.append(f"cells.{axis} is not an axis")
    for axis, (rows, columns) in AXES.items():
        column_ids = ids[columns] if columns else None
        for label, cell in axis_cells(axis, cells.get(axis), ids[rows], column_ids, errors):
            problem = cell_problem(label, cell, root)
            if problem:
                errors.append(problem)
    return errors


def axis_states(document):
    """Return {axis: [(label, cell)]} of a valid matrix in declaration order."""
    result = {}
    for axis, (rows, columns) in AXES.items():
        row_ids = [member["id"] for member in document[rows]]
        column_ids = [member["id"] for member in document[columns]] if columns else None
        result[axis] = axis_cells(axis, document["cells"][axis], row_ids, column_ids, [])
    return result


def _escape(text):
    return "" if text is None else str(text).replace("|", "\\|")


def _table(header, rows):
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines.extend("| " + " | ".join(_escape(value) for value in row) + " |" for row in rows)
    return lines + [""]


def _counts_table(cells_by_axis):
    rows = []
    totals = [0] * (len(STATES) + 1)
    for axis, cells in cells_by_axis.items():
        counts = [len(cells)] + [sum(1 for _, cell in cells if cell["state"] == s) for s in STATES]
        totals = [a + b for a, b in zip(totals, counts)]
        rows.append([f"`{axis}`"] + [str(value) for value in counts])
    rows.append(["total"] + [str(value) for value in totals])
    return _table(["Axis", "Cells"] + [f"`{s}`" for s in STATES], rows)


def _grid(document, axis, columns):
    column_ids = [member["id"] for member in document[columns]]
    rows = []
    for family in document["families"]:
        line = document["cells"][axis][family["id"]]
        rows.append([f"`{family['id']}`"] + [f"`{line[column]['state']}`" for column in column_ids])
    return _table(["Family"] + [f"`{column}`" for column in column_ids], rows)


def _members(document, name, header):
    keys = MEMBER_KEYS[name][1:]
    rows = [[f"`{member['id']}`"] + [member[key] if key == "title" else f"`{member[key]}`" for key in keys]
            for member in document[name]]
    return _table(header, rows)


def _details(cells_by_axis):
    rows = []
    for cells in cells_by_axis.values():
        for label, cell in cells:
            if cell["state"] != "not_run" or cell["test"] or cell["reason"] or cell["issue"]:
                rows.append([label, f"`{cell['state']}`", cell["test"] or "", cell["reason"] or "",
                             cell["issue"] or ""])
    if not rows:
        return ["Every cell is `not_run` and carries no test, reason or issue.", ""]
    return _table(["Cell", "State", "Test", "Reason", "Owner issue"], rows)


def render(document):
    """Return the page's generated tables for a valid matrix."""
    cells_by_axis = axis_states(document)
    negatives = [[f"`{member['id']}`", member["title"],
                  f"`{document['cells']['graph_negative'][member['id']]['state']}`"]
                 for member in document["graph_negatives"]]
    lines = ["### Cell counts", ""] + _counts_table(cells_by_axis)
    lines += ["### Families", ""] + _members(document, "families", ["Family", "Title", "Release"])
    lines += ["### Surfaces", ""] + _members(document, "surfaces", ["Surface", "Title"])
    lines += ["### Graph rows", ""] + _members(document, "graph_rows", ["Graph row", "Title"])
    lines += ["### Conditions", ""] + _members(document, "conditions", ["Condition", "Title"])
    lines += ["### Family x surface", ""] + _grid(document, "family_surface", "surfaces")
    lines += ["### Family x graph", ""] + _grid(document, "family_graph", "graph_rows")
    lines += ["### Family x condition", ""] + _grid(document, "family_condition", "conditions")
    lines += ["### Graph negatives", ""] + _table(["Graph negative", "Title", "State"], negatives)
    lines += ["### Cells with a test, a reason or an owner issue", ""] + _details(cells_by_axis)
    return "\n".join(lines).rstrip("\n") + "\n"


def generated_section(text):
    """Return the page text between the two marker lines, or None without both markers."""
    lines = text.split("\n")
    if lines.count(BEGIN) != 1 or lines.count(END) != 1:
        return None
    begin, end = lines.index(BEGIN), lines.index(END)
    if end < begin:
        return None
    return "\n".join(lines[begin + 1:end])


def page_problem(document, page):
    try:
        text = pathlib.Path(page).read_text(encoding="utf-8")
    except OSError as error:
        return f"cannot read {page}: {error.strerror}"
    section = generated_section(text)
    if section is None:
        return f"{page} needs exactly one generated section between the marker lines {BEGIN} and {END}"
    if section.strip("\n") != render(document).strip("\n"):
        return (f"the generated tables of {page} differ from the matrix; "
                "replace them with the output of scripts/offline_acceptance_matrix.py render")
    return None


def _report(messages):
    for message in messages:
        print(PREFIX + message, file=sys.stderr)
    return 1 if messages else 0


def run_check(root, matrix, page, require_complete):
    document = load(matrix)
    errors = validate(document, root)
    if errors:
        return _report(errors)
    problem = page_problem(document, page)
    if problem:
        return _report([problem])
    cells_by_axis = axis_states(document)
    open_cells = {axis: sum(1 for _, c in cells if c["state"] == "not_run") for axis, cells in cells_by_axis.items()}
    total = sum(len(cells) for cells in cells_by_axis.values())
    per_axis = ", ".join(f"{axis} {count}" for axis, count in open_cells.items())
    if require_complete and any(open_cells.values()):
        return _report([f"incomplete: {sum(open_cells.values())} cells not_run ({per_axis})"])
    print(f"{PREFIX}ok: {total} cells, {sum(open_cells.values())} not_run ({per_axis})")
    return 0


def run_render(root, matrix):
    document = load(matrix)
    errors = validate(document, root)
    if errors:
        return _report(errors)
    sys.stdout.write(render(document))
    return 0


def parse_arguments(argv):
    common = argparse.ArgumentParser(add_help=False)
    common.add_argument("--root", default=str(ROOT), help="repository root that named tests are resolved against")
    common.add_argument("--matrix", help="matrix file (default: " + MATRIX_PATH + " under the root)")
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    commands = parser.add_subparsers(dest="command", required=True)
    check = commands.add_parser("check", parents=[common], help="validate the matrix and the page")
    check.add_argument("--page", help="page file (default: " + PAGE_PATH + " under the root)")
    check.add_argument("--require-complete", action="store_true", help="also fail on any not_run cell")
    commands.add_parser("render", parents=[common], help="print the page's generated tables")
    return parser.parse_args(argv)


def main(argv=None):
    arguments = parse_arguments(argv)
    root = pathlib.Path(arguments.root)
    matrix = pathlib.Path(arguments.matrix) if arguments.matrix else root / MATRIX_PATH
    try:
        if arguments.command == "render":
            return run_render(root, matrix)
        page = pathlib.Path(arguments.page) if arguments.page else root / PAGE_PATH
        return run_check(root, matrix, page, arguments.require_complete)
    except MatrixError as error:
        return _report([str(error)])


if __name__ == "__main__":
    sys.exit(main())
